function runNote(token, extra, maxSections) {
  const s = P('startNote', Object.assign({ topic: 'Explain Everything About Input and Output Devices.', language: 'simple-english', level: 'beginner', depth: 'detailed' }, extra || {}), token, 'req-' + Math.random().toString(36).slice(2, 12));
  if (!s.ok) return { start: s };
  const done = [];
  s.data.sections.slice(0, maxSections === undefined ? 999 : maxSections).forEach((x, i) => done.push(P('generateSection', { noteId: s.data.note.id, index: i }, token, 'sec-' + Math.random().toString(36).slice(2, 12))));
  return { start: s, sections: done, id: s.data.note.id };
}

